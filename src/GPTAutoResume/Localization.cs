    public static string Get(string language, string key)
    {
        var normalized = Text.ContainsKey(language) ? language : "zh-TW";
        return Text[normalized].TryGetValue(key, out var value) ? value : key;
    }

    public static string DefaultResumeText(string language) => Get(language, "DefaultResumeText");

    public static bool IsDefaultResumeText(string value) =>
        Text.Values.Any(map => string.Equals(map["DefaultResumeText"], value, StringComparison.Ordinal));

    public static IReadOnlyList<ResumePolicyOption> GetResumePolicies(string language) =>
    [
        new(GPTAutoResume.Core.ResumePolicy.NotifyOnly, Get(language, "PolicyNotifyOnly")),
        new(GPTAutoResume.Core.ResumePolicy.ConfirmBeforeResume, Get(language, "PolicyConfirmBeforeResume")),
        new(GPTAutoResume.Core.ResumePolicy.AutomaticForegroundResume, Get(language, "PolicyAutomaticForegroundResume"))
    ];
